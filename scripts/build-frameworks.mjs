/**
 * Pull the framework catalogue out of the product and into the site.
 *
 * The source of truth is sal/internal/framework_catalog/data/*.yaml — the same
 * files the app reads. Nothing here is written by hand, so a page can never
 * claim a framework the product does not actually carry.
 *
 *   node scripts/build-frameworks.mjs
 *
 * Re-run whenever the catalogue changes.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const here = dirname(fileURLToPath(import.meta.url));
const SAL = join(here, '../../sal/internal');
const CATALOG = join(SAL, 'framework_catalog/data');
const COVERAGE = join(SAL, 'compliance/data/framework_coverage.json');
const OUT = join(here, '../src/data');

const COUNTRY = {
  GB: { name: 'United Kingdom', adj: 'UK' },
  IE: { name: 'Ireland', adj: 'Irish' },
  US: { name: 'United States', adj: 'US' },
  AU: { name: 'Australia', adj: 'Australian' },
  NZ: { name: 'New Zealand', adj: 'New Zealand' },
  IN: { name: 'India', adj: 'Indian' },
};

const VERTICAL = {
  general_clinic: 'General practice',
  dental: 'Dental',
  veterinary: 'Veterinary',
  allied_health: 'Allied health',
};

const CATEGORY = {
  inspection: 'Inspection',
  records: 'Records',
  'professional-conduct': 'Professional conduct',
  safety: 'Safety',
  billing: 'Billing and reimbursement',
};

const frameworks = readdirSync(CATALOG)
  .filter((f) => f.endsWith('.yaml'))
  .map((f) => {
    const d = yaml.load(readFileSync(join(CATALOG, f), 'utf8'));
    return {
      key: d.key,
      body: d.body,
      fullName: d.full_name,
      country: d.country,
      countryName: COUNTRY[d.country]?.name ?? d.country,
      category: d.category,
      categoryName: CATEGORY[d.category] ?? d.category,
      verticals: d.verticals ?? [],
      verticalNames: (d.verticals ?? []).map((v) => VERTICAL[v] ?? v),
      summary: (d.summary ?? '').trim(),
      longSummary: (d.long_summary ?? '').trim(),
      keyTerms: d.key_terms ?? [],
      formsImplicated: d.forms_implicated ?? [],
      retentionYears: d.retention_years ?? null,
      currencyDate: d.currency_date ?? null,
      sourceUrls: d.source_urls ?? [],
      clauses: (d.clauses ?? []).map((c) => ({
        ref: c.ref,
        title: c.title,
        text: (c.text ?? '').trim(),
        implication: (c.implication ?? '').trim(),
      })),
    };
  })
  .sort((a, b) => a.country.localeCompare(b.country) || a.body.localeCompare(b.body));

/* Scored frameworks: the four-state coverage the product actually computes.
   Only the headline counts travel to the site — the full tree stays in the app. */
const coverage = JSON.parse(readFileSync(COVERAGE, 'utf8')).map((f) => {
  const c = f.counts;
  const total = Object.values(c).reduce((a, b) => a + b, 0);
  const inScope = total - c.out_of_scope;
  return {
    id: f.id,
    name: f.name,
    edition: f.edition || null,
    total,
    inScope,
    measuredNow: c.measured_now,
    needsData: c.needs_data,
    comingSoon: c.coming_soon,
    outOfScope: c.out_of_scope,
    pct: Math.round((c.measured_now / inScope) * 100),
    /* Top-level chapter codes, for showing what a framework is made of. */
    groups: (f.groups ?? []).map((g) => ({ code: g.code, title: g.title })),
  };
});

/* Two files on purpose. The nav and the index only need names and labels, and
   pulling every long summary and clause into the header would put ~60kB of
   gzipped text on the landing page to render a menu. The full record is only
   imported by the detail route. */
const light = frameworks.map(({ longSummary, clauses, keyTerms, formsImplicated, sourceUrls, ...rest }) => ({
  ...rest,
  clauseCount: clauses.length,
}));

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'frameworks-index.json'), JSON.stringify(light));
writeFileSync(join(OUT, 'frameworks.json'), JSON.stringify(frameworks));
writeFileSync(join(OUT, 'coverage.json'), JSON.stringify(coverage, null, 1));
/* Headline counts, so a nav or a footer can state the breadth without pulling
   the whole catalogue into every page's bundle. */
writeFileSync(join(OUT, 'frameworkStats.json'), JSON.stringify({
  frameworks: frameworks.length,
  bodies: new Set(frameworks.map((f) => f.body)).size,
  countries: new Set(frameworks.map((f) => f.country)).size,
  verticals: new Set(frameworks.flatMap((f) => f.verticals)).size,
  clauses: frameworks.reduce((n, f) => n + f.clauses.length, 0),
}, null, 1));

writeFileSync(
  join(OUT, 'frameworkKeys.mjs'),
  `// Generated by scripts/build-frameworks.mjs — used by prerender.mjs.\nexport const frameworkKeys = ${JSON.stringify(frameworks.map((f) => f.key))};\n`
);

const countries = [...new Set(frameworks.map((f) => f.country))];
const verticals = [...new Set(frameworks.flatMap((f) => f.verticals))];
const bodies = [...new Set(frameworks.map((f) => f.body))];
console.log(
  `${frameworks.length} frameworks · ${bodies.length} bodies · ${countries.length} countries ` +
  `· ${verticals.length} verticals · ${frameworks.reduce((n, f) => n + f.clauses.length, 0)} clauses`
);
console.log(`${coverage.length} scored frameworks: ${coverage.map((c) => `${c.id} ${c.pct}%`).join(', ')}`);
